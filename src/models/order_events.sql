CREATE TABLE order_events (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    event VARCHAR(20) NOT NULL CHECK (event IN ('SUBMIT', 'RISK_PASS', 'RISK_FAIL', 'ACK', 'PARTIAL_FILL', 'FILL', 'CANCEL_REQUEST', 'CANCELLED', 'EXPIRE')),
    from_status VARCHAR(20) NOT NULL CHECK (from_status IN ('NEW', 'PENDING_RISK', 'REJECTED', 'ACCEPTED', 'WORKING', 'PARTIALLY_FILLED', 'FILLED', 'PENDING_CANCEL', 'CANCELLED', 'EXPIRED')),
    to_status VARCHAR(20) NOT NULL CHECK (to_status IN ('NEW', 'PENDING_RISK', 'REJECTED', 'ACCEPTED', 'WORKING', 'PARTIALLY_FILLED', 'FILLED', 'PENDING_CANCEL', 'CANCELLED', 'EXPIRED')),
    detail JSONB,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_order_events_order ON order_events (order_id);
